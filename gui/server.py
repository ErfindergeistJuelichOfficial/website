"""
GUI config editor - local HTTP server.
Serves index.html + REST API for the configs in Public/Configs (Nextcloud):
chronicle.json, links.json, tags.json, downloads.json and galerie.json.
History/undo is not kept here - the Nextcloud versions every file.
"""
import email.utils
import hashlib
import http.server
import json
import os
import mimetypes
import subprocess
import tempfile
import threading
import time
import urllib.error
import urllib.request
from pathlib import Path
from urllib.parse import urlparse, parse_qs

CONFIG_DIR     = Path('/configs')
SOURCE_DIR     = Path('/source')
DOWNLOADS_DIR  = Path('/downloads')
GALERIE_JSON   = CONFIG_DIR / 'galerie.json'
DOWNLOADS_JSON = CONFIG_DIR / 'downloads.json'

GITHUB_DISPATCH_URL = ('https://api.github.com/repos/ErfindergeistJuelichOfficial/website'
                       '/actions/workflows/deploy-share.yml/dispatches')

THUMB_CACHE_DIR = Path(tempfile.gettempdir()) / 'gui-thumb-cache'
THUMB_MAX_PX    = 320  # picker grid shows 120 CSS px; 320 covers HiDPI displays

# Album fields maintained by the GUI; all other fields in a galerie.json entry
# (imageCount, previewThumbnail, hasPart) are generated by process.py.
ALBUM_FIELDS = ('title', 'description', 'consent_collected', 'chronicle_id',
                'link_ids', 'preview', 'blur', 'no_blur')

# ---------------------------------------------------------------------------
# Galerie job state
# ---------------------------------------------------------------------------

_job_lock = threading.Lock()
_job: dict = {
    'status': 'idle',   # 'idle' | 'running' | 'done' | 'error'
    'action': None,
    'lines':  [],
    'rc':     None,
    'proc':   None,     # subprocess.Popen while running
}

# -u: unbuffered stdout, so progress lines reach the SSE stream immediately
# instead of arriving in 4-8 KB chunks minutes later
_GALERIE_CMDS = {
    'process':  ['python', '-u', '/app/process.py'],
}

# Serialises read-modify-write of galerie.json / downloads.json within this server
_file_lock = threading.Lock()


def _job_running() -> bool:
    with _job_lock:
        return _job['status'] == 'running'


def _run_galerie_job(cmd: list, env: dict) -> None:
    with _job_lock:
        _job['lines'] = []
        _job['rc']    = None

    try:
        proc = subprocess.Popen(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            env=env,
        )
        with _job_lock:
            _job['proc'] = proc

        for line in proc.stdout:
            with _job_lock:
                _job['lines'].append(line.rstrip('\n'))
        proc.wait()
        rc = proc.returncode
    except Exception as exc:
        with _job_lock:
            _job['lines'].append(f'[ERROR] {exc}')
            _job['status'] = 'error'
            _job['rc']     = -1
            _job['proc']   = None
        return

    with _job_lock:
        _job['rc']     = rc
        _job['status'] = 'done' if rc == 0 else 'error'
        _job['proc']   = None

ALLOWED_CONFIG = {'chronicle', 'links', 'tags'}
IMAGE_EXTENSIONS = {'.jpg', '.jpeg', '.png', '.gif', '.webp', '.tif', '.tiff', '.bmp'}

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _read_json(path: Path) -> object:
    with open(path, encoding='utf-8-sig') as f:
        return json.load(f)


def _write_json(path: Path, obj: object, compact: bool = False) -> None:
    """Atomic write (tmp + rename) so the Nextcloud client never syncs a half-written file."""
    with tempfile.NamedTemporaryFile(
        'w', dir=path.parent, delete=False, suffix='.tmp', encoding='utf-8'
    ) as f:
        if compact:
            json.dump(obj, f, ensure_ascii=False, separators=(',', ':'))
        else:
            json.dump(obj, f, ensure_ascii=False, indent=2)
        f.write('\n')
        tmp = f.name
    os.replace(tmp, str(path))


def _safe_is_dir(p: Path) -> bool:
    """is_dir() that treats unreadable entries (e.g. SELinux-denied files in a
    synced source folder) as non-existent instead of raising."""
    try:
        return p.is_dir()
    except OSError:
        return False


def _safe_is_file(p: Path) -> bool:
    """is_file() that treats unreadable entries as non-existent instead of raising."""
    try:
        return p.is_file()
    except OSError:
        return False


def _valid_rel(rel: str) -> bool:
    return bool(rel) and '..' not in rel and not rel.startswith('/')


def _validate_image_path(rel: str, filename: str) -> Path | None:
    """Return image path if safe and is an image file, else None."""
    if not _valid_rel(rel):
        return None
    if not filename or '..' in filename or '/' in filename or '\\' in filename:
        return None
    img = SOURCE_DIR / rel / filename
    if img.suffix.lower() not in IMAGE_EXTENSIONS or not _safe_is_file(img):
        return None
    return img


def _thumbnail_for(img_path: Path) -> Path | None:
    """Return a cached WebP thumbnail for img_path, generating it on first use.
    Cache key includes mtime + size, so edited source images refresh naturally."""
    try:
        stat = img_path.stat()
        key  = hashlib.sha1(
            f'{img_path}|{stat.st_mtime_ns}|{stat.st_size}'.encode()
        ).hexdigest()
        thumb = THUMB_CACHE_DIR / f'{key}.webp'
        if thumb.is_file():
            return thumb
        from PIL import Image, ImageOps
        THUMB_CACHE_DIR.mkdir(parents=True, exist_ok=True)
        with Image.open(img_path) as img:
            img = ImageOps.exif_transpose(img)
            img.thumbnail((THUMB_MAX_PX, THUMB_MAX_PX))
            img.convert('RGB').save(thumb, 'WEBP', quality=70)
        return thumb
    except Exception:
        return None


# ---------------------------------------------------------------------------
# galerie.json / downloads.json
# ---------------------------------------------------------------------------

def _catalog(path: Path, name: str, description: str) -> dict:
    """Read a DataCatalog config file, or return an empty skeleton when it does not exist yet."""
    if path.is_file():
        data = _read_json(path)
        if isinstance(data, dict) and isinstance(data.get('hasPart'), list):
            return data
    return {
        '@context':    'https://schema.org',
        '@type':       'DataCatalog',
        '@id':         f'https://share.erfindergeist.org/config/{path.name}',
        'name':        name,
        'description': description,
        'hasPart':     [],
    }


def _load_galerie() -> dict:
    return _catalog(GALERIE_JSON, 'Galerie - Erfindergeist Jülich e.V.',
                    'Foto-Galerie des Erfindergeist Jülich e.V. (Album-Konfiguration und Bildlisten).')


def _load_downloads() -> dict:
    return _catalog(DOWNLOADS_JSON, 'Downloads - Erfindergeist Jülich e.V.',
                    'Metadaten aller Download-Ordner.')


def _find(data: dict, rel: str) -> dict | None:
    return next((e for e in data['hasPart'] if isinstance(e, dict) and e.get('path') == rel), None)


def _download_folders() -> list[str]:
    """Folders known locally (share/downloads) or in downloads.json - the real files live on the server."""
    folders = {e['path'] for e in _load_downloads()['hasPart'] if isinstance(e, dict) and e.get('path')}
    if DOWNLOADS_DIR.is_dir():
        for entry in DOWNLOADS_DIR.rglob('*'):
            if _safe_is_dir(entry):
                folders.add(entry.relative_to(DOWNLOADS_DIR).as_posix())
    return sorted(folders)


# ---------------------------------------------------------------------------
# Request handler
# ---------------------------------------------------------------------------

class Handler(http.server.BaseHTTPRequestHandler):

    def log_message(self, fmt, *args):  # suppress default access log noise
        pass

    def _send(self, code: int, body: bytes, content_type: str = 'application/json') -> None:
        self.send_response(code)
        self.send_header('Content-Type', content_type)
        self.send_header('Content-Length', str(len(body)))
        self.end_headers()
        try:
            self.wfile.write(body)
        except (BrokenPipeError, ConnectionResetError):
            pass

    def _json(self, code: int, obj: object) -> None:
        self._send(code, json.dumps(obj, ensure_ascii=False).encode())

    def _error(self, code: int, msg: str) -> None:
        self._json(code, {'error': msg})

    def _read_body(self) -> bytes:
        length = int(self.headers.get('Content-Length', 0))
        return self.rfile.read(length)

    # --- Static files -------------------------------------------------------

    def _serve_file(self, path: Path) -> None:
        if not path.is_file():
            self._error(404, 'Not found')
            return
        mime, _ = mimetypes.guess_type(str(path))
        data = path.read_bytes()
        self.send_response(200)
        self.send_header('Content-Type', mime or 'application/octet-stream')
        self.send_header('Content-Length', str(len(data)))
        self.send_header('Cache-Control', 'no-store')
        self.end_headers()
        self.wfile.write(data)

    def _serve_image(self, path: Path) -> None:
        """Serve an album image with Last-Modified/If-Modified-Since caching,
        so the picker does not re-download images on every open."""
        try:
            stat = path.stat()
        except OSError:
            self._error(404, 'Not found')
            return
        last_mod = email.utils.formatdate(stat.st_mtime, usegmt=True)
        if self.headers.get('If-Modified-Since') == last_mod:
            self.send_response(304)
            self.send_header('Cache-Control', 'private, max-age=3600')
            self.send_header('Last-Modified', last_mod)
            self.end_headers()
            return
        mime, _ = mimetypes.guess_type(str(path))
        data = path.read_bytes()
        self.send_response(200)
        self.send_header('Content-Type', mime or 'application/octet-stream')
        self.send_header('Content-Length', str(len(data)))
        self.send_header('Cache-Control', 'private, max-age=3600')
        self.send_header('Last-Modified', last_mod)
        self.end_headers()
        try:
            self.wfile.write(data)
        except (BrokenPipeError, ConnectionResetError):
            pass

    # --- Routing ------------------------------------------------------------

    def do_GET(self):
        parsed = urlparse(self.path)
        p = parsed.path
        qs = parse_qs(parsed.query)

        if p == '/':
            self._serve_file(Path('/app/index.html'))
        elif p in ('/style.css', '/app.js'):
            self._serve_file(Path('/app') / p[1:])
        elif p == '/api/all':
            self._api_all()
        elif p == '/api/albums':
            self._api_albums()
        elif p == '/api/album/dirs':
            self._api_album_dirs()
        elif p == '/api/album/images':
            self._api_album_images(qs)
        elif p == '/api/album/image':
            self._api_album_image(qs)
        elif p == '/api/album':
            self._api_album_get(qs)
        elif p == '/api/downloads':
            self._api_downloads()
        elif p == '/api/download-entries':
            self._api_download_entries()
        elif p == '/api/download-meta':
            self._api_download_meta_get(qs)
        elif p == '/api/download-files':
            self._api_download_files(qs)
        elif p == '/api/galerie/status':
            self._api_galerie_status()
        elif p == '/api/galerie/stream':
            self._api_galerie_stream()
        else:
            self._error(404, 'Not found')

    def do_POST(self):
        parsed = urlparse(self.path)
        p = parsed.path
        qs = parse_qs(parsed.query)

        if p == '/api/save/chronicle':
            self._api_save('chronicle')
        elif p == '/api/save/links':
            self._api_save('links')
        elif p == '/api/save/tags':
            self._api_save('tags')
        elif p == '/api/album':
            self._api_album_post(qs)
        elif p == '/api/album/delete':
            self._api_album_delete(qs)
        elif p == '/api/download-meta':
            self._api_download_meta_post(qs)
        elif p == '/api/galerie/run':
            self._api_galerie_run()
        elif p == '/api/galerie/cancel':
            self._api_galerie_cancel()
        elif p == '/api/publish':
            self._api_publish()
        else:
            self._error(404, 'Not found')

    # --- API handlers -------------------------------------------------------

    def _read_json_body(self) -> object | None:
        """Parse the request body; sends 400 and returns None on invalid JSON."""
        try:
            return json.loads(self._read_body())
        except json.JSONDecodeError as exc:
            self._error(400, f'Invalid JSON: {exc}')
            return None

    def _api_all(self) -> None:
        result = {}
        for name in ('chronicle', 'links', 'tags'):
            path = CONFIG_DIR / f'{name}.json'
            result[name] = _read_json(path) if path.is_file() else {}
        self._json(200, result)

    def _api_save(self, name: str) -> None:
        if name not in ALLOWED_CONFIG:
            self._error(400, 'Unknown file')
            return
        new_obj = self._read_json_body()
        if new_obj is None:
            return
        _write_json(CONFIG_DIR / f'{name}.json', new_obj)
        self._json(200, {'ok': True})

    # --- Albums (galerie.json) ---------------------------------------------

    def _api_album_dirs(self) -> None:
        """Folders in Mitglieder/Galerie that have no album entry yet."""
        if not SOURCE_DIR.is_dir():
            self._json(200, [])
            return
        existing = {a.get('path') for a in _load_galerie()['hasPart'] if isinstance(a, dict)}
        dirs = []
        for d in sorted(SOURCE_DIR.rglob('*')):
            if not _safe_is_dir(d):
                continue
            rel = d.relative_to(SOURCE_DIR).as_posix()
            if rel and rel != '.' and rel not in existing:
                dirs.append(rel)
        self._json(200, dirs)

    def _api_albums(self) -> None:
        albums = []
        for a in sorted(_load_galerie()['hasPart'], key=lambda e: str(e.get('path', ''))):
            if not isinstance(a, dict) or not a.get('path'):
                continue
            albums.append({
                'path':              a['path'],
                'title':             a.get('title', a['path']),
                'description':       a.get('description', ''),
                'chronicle_id':      a.get('chronicle_id', ''),
                'consent_collected': bool(a.get('consent_collected', False)),
            })
        self._json(200, albums)

    def _api_album_images(self, qs: dict) -> None:
        rel = (qs.get('path') or [''])[0]
        if not _valid_rel(rel):
            self._error(400, 'Invalid path')
            return
        album_dir = SOURCE_DIR / rel
        if not album_dir.is_dir():
            self._error(404, 'Album not found')
            return
        files = sorted(
            f.name for f in album_dir.iterdir()
            if f.suffix.lower() in IMAGE_EXTENSIONS and _safe_is_file(f)
        )
        self._json(200, files)

    def _api_album_image(self, qs: dict) -> None:
        rel      = (qs.get('path') or [''])[0]
        filename = (qs.get('file') or [''])[0]
        img_path = _validate_image_path(rel, filename)
        if img_path is None:
            self._error(404, 'Image not found')
            return
        if (qs.get('thumb') or [''])[0] == '1':
            thumb = _thumbnail_for(img_path)
            if thumb is not None:
                self._serve_image(thumb)
                return
        self._serve_image(img_path)

    def _api_album_get(self, qs: dict) -> None:
        rel = (qs.get('path') or [''])[0]
        album = _find(_load_galerie(), rel) if _valid_rel(rel) else None
        if album is None:
            self._error(404, f'Album not found: {rel!r}')
            return
        self._json(200, {k: album[k] for k in ALBUM_FIELDS if k in album})

    def _api_album_post(self, qs: dict) -> None:
        """Create or replace the config fields of one album; generated fields stay untouched."""
        rel = (qs.get('path') or [''])[0]
        if not _valid_rel(rel):
            self._error(400, 'Invalid path')
            return
        if _job_running():
            self._error(409, 'Bildverarbeitung laeuft - bitte warten, bis sie fertig ist.')
            return
        new_cfg = self._read_json_body()
        if new_cfg is None:
            return
        if not isinstance(new_cfg, dict) or not isinstance(new_cfg.get('title'), str):
            self._error(400, 'title is required')
            return
        with _file_lock:
            data  = _load_galerie()
            album = _find(data, rel)
            if album is None:
                if not (SOURCE_DIR / rel).is_dir():
                    self._error(404, f'Source folder not found: {rel!r}')
                    return
                album = {'@type': 'ImageGallery', 'path': rel, 'imageCount': 0, 'hasPart': []}
                data['hasPart'].append(album)
            for key in ALBUM_FIELDS:
                album.pop(key, None)
            album.update({k: new_cfg[k] for k in ALBUM_FIELDS if k in new_cfg})
            album['consent_collected'] = bool(new_cfg.get('consent_collected', False))
            _write_json(GALERIE_JSON, data, compact=True)
        self._json(200, {'ok': True})

    def _api_album_delete(self, qs: dict) -> None:
        """Remove the album entry; process.py deletes the orphaned WebP files on its next run."""
        rel = (qs.get('path') or [''])[0]
        if not _valid_rel(rel):
            self._error(400, 'Invalid path')
            return
        if _job_running():
            self._error(409, 'Bildverarbeitung laeuft - bitte warten, bis sie fertig ist.')
            return
        with _file_lock:
            data = _load_galerie()
            if _find(data, rel) is None:
                self._error(404, 'Album not found')
                return
            data['hasPart'] = [a for a in data['hasPart'] if not (isinstance(a, dict) and a.get('path') == rel)]
            _write_json(GALERIE_JSON, data, compact=True)
        self._json(200, {'ok': True})

    # --- Downloads (downloads.json) ----------------------------------------

    def _api_downloads(self) -> None:
        known = {e.get('path') for e in _load_downloads()['hasPart'] if isinstance(e, dict)}
        self._json(200, [{'path': rel, 'hasMeta': rel in known} for rel in _download_folders() if rel])

    def _api_download_entries(self) -> None:
        """Flat list of all file entries across all folders in downloads.json."""
        entries = []
        for folder in sorted(_load_downloads()['hasPart'], key=lambda e: str(e.get('path', ''))):
            if not isinstance(folder, dict):
                continue
            for part in (folder.get('hasPart') or []):
                title = part.get('title', '') if isinstance(part, dict) else ''
                if title:
                    entries.append({
                        'name':        title,
                        'folder':      folder.get('path', ''),
                        'description': part.get('description', ''),
                        'link_ids':    part.get('link_ids') or [],
                        'tags':        part.get('tags') or [],
                    })
        self._json(200, entries)

    def _api_download_meta_get(self, qs: dict) -> None:
        rel = (qs.get('path') or [''])[0]
        if not _valid_rel(rel) or rel not in _download_folders():
            self._error(404, f'Download folder not found: {rel!r}')
            return
        folder = _find(_load_downloads(), rel) or {}
        self._json(200, {
            '@type':       'DataCatalog',
            'path':        rel,
            'name':        folder.get('name', rel.split('/')[-1]),
            'description': folder.get('description', ''),
            'hasPart':     folder.get('hasPart', []),
        })

    def _api_download_meta_post(self, qs: dict) -> None:
        rel = (qs.get('path') or [''])[0]
        if not _valid_rel(rel) or rel not in _download_folders():
            self._error(404, f'Download folder not found: {rel!r}')
            return
        new_meta = self._read_json_body()
        if new_meta is None:
            return
        if not isinstance(new_meta, dict):
            self._error(400, 'Expected an object')
            return
        with _file_lock:
            data   = _load_downloads()
            folder = _find(data, rel)
            if folder is None:
                folder = {'@type': 'DataCatalog', 'path': rel}
                data['hasPart'].append(folder)
                data['hasPart'].sort(key=lambda e: str(e.get('path', '')))
            folder['name']        = new_meta.get('name') or rel.split('/')[-1]
            folder['description'] = new_meta.get('description', '')
            folder['hasPart']     = new_meta.get('hasPart') or []
            _write_json(DOWNLOADS_JSON, data)
        self._json(200, {'ok': True})

    def _api_download_files(self, qs: dict) -> None:
        """Files present in the local share/downloads folder (may be empty - files live on the server)."""
        rel = (qs.get('path') or [''])[0]
        if not _valid_rel(rel):
            self._error(400, 'Invalid path')
            return
        folder = DOWNLOADS_DIR / rel
        if not folder.is_dir():
            self._json(200, [])
            return
        files = sorted(
            f.name for f in folder.iterdir()
            if not f.name.startswith('_') and not f.name.startswith('.') and _safe_is_file(f)
        )
        self._json(200, files)

    # --- Publish -------------------------------------------------------------

    def _api_publish(self) -> None:
        """Start the deploy-share workflow on GitHub (configs + images from the cloud to the server)."""
        token = os.environ.get('GITHUB_TOKEN', '').strip()
        if not token:
            self._error(503, 'GITHUB_TOKEN fehlt in gui/.env - Veroeffentlichen nicht moeglich.')
            return
        req = urllib.request.Request(
            GITHUB_DISPATCH_URL,
            data=json.dumps({'ref': 'main'}).encode(),
            method='POST',
            headers={
                'Accept':               'application/vnd.github+json',
                'Authorization':        f'Bearer {token}',
                'X-GitHub-Api-Version': '2022-11-28',
                'User-Agent':           'erfindergeist-gui',
            },
        )
        try:
            with urllib.request.urlopen(req, timeout=20):
                pass
        except urllib.error.HTTPError as exc:
            self._error(502, f'GitHub antwortet mit HTTP {exc.code}')
            return
        except (urllib.error.URLError, TimeoutError) as exc:
            self._error(502, f'GitHub nicht erreichbar: {exc}')
            return
        self._json(202, {'ok': True})

    # --- Galerie job handlers ------------------------------------------------

    def _api_galerie_status(self) -> None:
        with _job_lock:
            snap = {k: v for k, v in _job.items() if k != 'proc'}
        self._json(200, snap)

    def _api_galerie_run(self) -> None:
        body = self._read_body()
        try:
            req = json.loads(body)
        except json.JSONDecodeError as exc:
            self._error(400, f'Invalid JSON: {exc}')
            return
        action = req.get('action', '')
        if action not in _GALERIE_CMDS:
            self._error(400, f'Unknown action: {action!r}')
            return
        with _job_lock:
            if _job['status'] == 'running':
                self._json(409, {'error': 'Job already running'})
                return
            _job['status'] = 'running'
            _job['action'] = action
        cmd = _GALERIE_CMDS[action]
        env = dict(os.environ)
        t = threading.Thread(target=_run_galerie_job, args=(cmd, env), daemon=True)
        t.start()
        self._json(202, {'ok': True, 'action': action})

    def _api_galerie_cancel(self) -> None:
        with _job_lock:
            if _job['status'] != 'running':
                self._json(409, {'error': 'No job running'})
                return
            proc = _job.get('proc')
        if proc is not None:
            try:
                proc.kill()
            except OSError:
                pass
        self._json(200, {'ok': True})

    def _api_galerie_stream(self) -> None:
        self.send_response(200)
        self.send_header('Content-Type', 'text/event-stream')
        self.send_header('Cache-Control', 'no-cache')
        self.send_header('X-Accel-Buffering', 'no')
        self.end_headers()

        sent = 0
        try:
            while True:
                with _job_lock:
                    status   = _job['status']
                    lines    = _job['lines']
                    new      = lines[sent:]
                    rc       = _job['rc']

                for line in new:
                    self.wfile.write(f'data: {line}\n\n'.encode())
                    sent += 1

                if new:
                    self.wfile.flush()

                if status in ('done', 'error') and sent >= len(lines):
                    payload = json.dumps({'rc': rc, 'status': status})
                    self.wfile.write(f'event: done\ndata: {payload}\n\n'.encode())
                    self.wfile.flush()
                    return

                if status == 'idle':
                    payload = json.dumps({'rc': None, 'status': 'idle'})
                    self.wfile.write(f'event: done\ndata: {payload}\n\n'.encode())
                    self.wfile.flush()
                    return

                time.sleep(0.15)
        except (BrokenPipeError, ConnectionResetError, OSError):
            pass


